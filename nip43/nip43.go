// LeaveRequest is a parsed kind:28936 event. It carries no data beyond the
// NIP-70 protected tag -- the leaving pubkey is event.PubKey itself.
type LeaveRequest struct{}

// ParseLeaveRequest parses and structurally validates a kind:28936 event.
// It does not check the created_at freshness window -- see
// ValidateFreshness.
func ParseLeaveRequest(event *nip01.Event) (*LeaveRequest, error) {
	if event.Kind != KindLeaveRequest {
		return nil, fmt.Errorf("%w: got %d, want %d", ErrWrongKind, event.Kind, KindLeaveRequest)
	}
	if !hasProtectedTag(event.Tags) {
		return nil, ErrMissingProtectedTag
	}
	return &LeaveRequest{}, nil
}

// NewLeaveRequest builds an unsigned kind:28936 event. Caller must sign it
// with the leaving user's own private key.
func NewLeaveRequest(userPubkey string) *nip01.Event {
	return nip01.NewUnsignedEvent(KindLeaveRequest, userPubkey, "", []string{"-"})
}
